export function japanSeedProduct(
  spec: JapanSeedSpec,
  imageUrl: string | null = spec.imageUrl ?? (spec.brand === "MUJI" ? mujiImg(spec.sku) : null),
): DiscoveryProductInput {
  const image = isUsableProductImage(imageUrl) ? imageUrl : null;
  const sellerName = spec.brand === "MUJI" ? "無印良品 公式ネットストア" : "SHISEIDO 公式";
  return {
    id: spec.id,
    brand: spec.brand === "MUJI" ? "無印良品" : "SHISEIDO",
    productName: spec.productName,
    category: spec.category,
    subcategory: spec.subcategory,
    country: "Japan",
    description: spec.description,
    productImageUrl: image,
    productUrl: spec.officialUrl,
    officialUrl: spec.officialUrl,
    price: spec.price,
    currency: "JPY",
    sku: spec.sku,
    trendScore: 0,
    confidenceScore: image ? 80 : 50,
    discoverySource: "editorial",
    discoveredAt: NOW,
    attentionReason: image
      ? "公式オンラインストアに現行商品として掲載されています。"
      : "",
    status: image ? "approved" : "pending",
    trendTags: [],
    sources: [
      {
        id: `${spec.id}-src-1`,
        sourceType: "brand_official",
        sourceUrl: spec.officialUrl,
        sourceTitle: `${spec.brand === "MUJI" ? "無印良品" : "SHISEIDO"} ${spec.productName}`,
        sourceDomain: sourceDomain(spec.officialUrl),
        publishedAt: null,
        sourceExcerpt: spec.description,
        verificationStatus: "verified",
        sourceTier: 1,
        createdAt: NOW,
      },
    ],
    people: [],
    sales: [
      {
        id: `${spec.id}-sale-1`,
        sellerName,
        productUrl: spec.officialUrl,
        price: spec.price,
        currency: "JPY",
        availability: "unknown",
        officialStore: true,
        sellerKind: "official",
        affiliateUrl: null,
        lastVerifiedAt: NOW,
        createdAt: NOW,
      },
    ],
    createdAt: NOW,
    updatedAt: NOW,
  };
}

export function japanSeedToDiscovery(spec: JapanSeedSpec): DiscoveryProduct {
  const input = japanSeedProduct(spec);
  return {
    ...input,
    normalizedBrand: normalizeBrand(input.brand),
    normalizedProductName: normalizeProductName(input.productName),
    createdAt: input.createdAt ?? NOW,
    updatedAt: input.updatedAt ?? NOW,
  };
}

export const JAPAN_SEED_PRODUCTS: DiscoveryProduct[] = JAPAN_SEED_SPECS.map(japanSeedToDiscovery);
